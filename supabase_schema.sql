drop policy if exists profiles_read on public.profiles;
create policy profiles_read on public.profiles for select to authenticated using(true);
drop policy if exists profiles_update_self on public.profiles;
create policy profiles_update_self on public.profiles for update to authenticated using(id=auth.uid()) with check(id=auth.uid());

drop policy if exists friendship_read on public.friendships;
create policy friendship_read on public.friendships for select to authenticated using(requester=auth.uid() or addressee=auth.uid());
drop policy if exists friendship_delete on public.friendships;
create policy friendship_delete on public.friendships for delete to authenticated using(requester=auth.uid() or addressee=auth.uid());

drop policy if exists conversation_read on public.conversations;
create policy conversation_read on public.conversations for select to authenticated using(public.is_conversation_member(id));

drop policy if exists members_read on public.conversation_members;
create policy members_read on public.conversation_members for select to authenticated using(public.is_conversation_member(conversation_id));
drop policy if exists members_update_self on public.conversation_members;
create policy members_update_self on public.conversation_members for update to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());

drop policy if exists messages_read on public.messages;
create policy messages_read on public.messages for select to authenticated using(public.is_conversation_member(conversation_id));
drop policy if exists messages_insert on public.messages;
create policy messages_insert on public.messages for insert to authenticated with check(sender_id=auth.uid() and public.is_conversation_member(conversation_id));
drop policy if exists messages_update_own on public.messages;
create policy messages_update_own on public.messages for update to authenticated using(sender_id=auth.uid()) with check(sender_id=auth.uid());
drop policy if exists messages_delete_own on public.messages;
create policy messages_delete_own on public.messages for delete to authenticated using(sender_id=auth.uid());

drop policy if exists reactions_read on public.message_reactions;
create policy reactions_read on public.message_reactions for select to authenticated using(public.is_conversation_member(conversation_id));
drop policy if exists reactions_insert on public.message_reactions;
create policy reactions_insert on public.message_reactions for insert to authenticated with check(user_id=auth.uid() and public.is_conversation_member(conversation_id));
drop policy if exists reactions_delete on public.message_reactions;
create policy reactions_delete on public.message_reactions for delete to authenticated using(user_id=auth.uid());

drop policy if exists typing_read on public.typing_states;
create policy typing_read on public.typing_states for select to authenticated using(public.is_conversation_member(conversation_id));
drop policy if exists typing_insert on public.typing_states;
create policy typing_insert on public.typing_states for insert to authenticated with check(user_id=auth.uid() and public.is_conversation_member(conversation_id));
drop policy if exists typing_update on public.typing_states;
create policy typing_update on public.typing_states for update to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());

