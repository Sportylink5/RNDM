create or replace function public.claim_daily_reward()
returns table(stars integer,xp integer,cash bigint)
language plpgsql security definer set search_path=public as $$
declare s integer:=15; x integer:=40; c bigint:=750;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  if exists(select 1 from public.daily_claims where user_id=auth.uid() and claim_date=current_date) then raise exception 'already claimed'; end if;
  insert into public.daily_claims(user_id,reward_stars,reward_xp,reward_cash) values(auth.uid(),s,x,c);
  update public.profiles set stars=stars+s,xp=xp+x where id=auth.uid();
  insert into public.game_wallets(user_id,balance) values(auth.uid(),c) on conflict(user_id) do update set balance=public.game_wallets.balance+excluded.balance,updated_at=now();
  return query select s,x,c;
end $$;
grant execute on function public.claim_daily_reward() to authenticated;

create or replace function public.rndm_leaderboard(limit_count integer default 50)
returns table(user_id uuid,username text,display_name text,avatar_url text,xp bigint,reputation integer,stars bigint,app_role text)
language sql stable security definer set search_path=public as $$
  select p.id,p.username,p.display_name,p.avatar_url,p.xp,p.reputation,p.stars,p.app_role
  from public.profiles p
  where not p.is_banned
  order by p.xp desc,p.reputation desc,p.created_at asc
  limit greatest(1,least(coalesce(limit_count,50),100));
$$;
grant execute on function public.rndm_leaderboard(integer) to authenticated;

