create or replace function public.random_chat_join_v24(p_mode text default 'text', p_language text default 'any', p_interest text default 'any')
returns table(match_status text, conversation_id uuid, matched_user_id uuid)
language plpgsql security definer set search_path=public as $$
declare me uuid:=auth.uid(); other_user uuid; cid uuid; existing public.random_queue%rowtype;
begin
  if me is null then raise exception 'not authenticated'; end if;
  if exists(select 1 from public.profiles where id=me and is_banned and (banned_until is null or banned_until>now())) then raise exception 'account banned'; end if;
  perform pg_advisory_xact_lock(83920417);
  delete from public.random_queue where (status='waiting' and updated_at<now()-interval '3 minutes') or (status='matched' and updated_at<now()-interval '15 minutes');
  select * into existing from public.random_queue where user_id=me;
  if found and existing.status='matched' and existing.conversation_id is not null then return query select 'matched'::text,existing.conversation_id,existing.matched_user_id; return; end if;
  insert into public.random_queue(user_id,status,matched_user_id,conversation_id,joined_at,updated_at,mode,language,interest)
  values(me,'waiting',null,null,now(),now(),coalesce(nullif(p_mode,''),'text'),coalesce(nullif(p_language,''),'any'),coalesce(nullif(p_interest,''),'any'))
  on conflict(user_id) do update set status='waiting',matched_user_id=null,conversation_id=null,joined_at=now(),updated_at=now(),mode=excluded.mode,language=excluded.language,interest=excluded.interest;
  select q.user_id into other_user from public.random_queue q
  join public.profiles pp on pp.id=q.user_id
  where q.user_id<>me and q.status='waiting' and q.updated_at>=now()-interval '3 minutes'
    and not (pp.is_banned and (pp.banned_until is null or pp.banned_until>now()))
    and q.mode=coalesce(nullif(p_mode,''),'text')
    and (p_language='any' or q.language='any' or q.language=p_language)
    and (p_interest='any' or q.interest='any' or q.interest=p_interest)
    and not exists(select 1 from public.friendships f where f.status='blocked' and ((f.requester=me and f.addressee=q.user_id) or (f.requester=q.user_id and f.addressee=me)))
  order by pp.reputation desc,q.joined_at asc limit 1;
  if other_user is null then return query select 'waiting'::text,null::uuid,null::uuid; return; end if;
  cid:=public.get_or_create_direct(other_user);
  update public.random_queue set status='matched',matched_user_id=other_user,conversation_id=cid,updated_at=now() where user_id=me;
  update public.random_queue set status='matched',matched_user_id=me,conversation_id=cid,updated_at=now() where user_id=other_user;
  return query select 'matched'::text,cid,other_user;
end $$;
grant execute on function public.random_chat_join_v24(text,text,text) to authenticated;

