create or replace function public.admin_resolve_report(report_id bigint, new_status text)
returns void language plpgsql security definer set search_path=public as $$
begin
  if not public.is_staff() then raise exception 'staff required'; end if;
  if new_status not in ('reviewing','resolved','rejected') then raise exception 'invalid status'; end if;
  update public.reports set status=new_status,moderator_id=auth.uid(),resolved_at=case when new_status in ('resolved','rejected') then now() else null end where id=report_id;
  perform public.admin_log('report_'||new_status,null,jsonb_build_object('report_id',report_id));
end $$;

