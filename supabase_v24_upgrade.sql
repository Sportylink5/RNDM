create or replace function public.role_rank(r text)
returns integer language sql immutable as $$
  select case lower(coalesce(r,'user'))
    when 'owner' then 50
    when 'admin' then 40
    when 'moderator' then 30
    when 'verified' then 20
    when 'premium' then 10
    else 0 end;
$$;

create or replace function public.is_staff(uid uuid default auth.uid())
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles p where p.id=uid and p.app_role in ('owner','admin','moderator'));
$$;

create or replace function public.is_admin(uid uuid default auth.uid())
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles p where p.id=uid and p.app_role in ('owner','admin'));
