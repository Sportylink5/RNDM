create or replace function public.admin_create_stock(
  p_ticker text,
  p_name text,
  p_price bigint,
  p_emoji text default '📈',
  p_description text default ''
)
returns uuid
language plpgsql
security definer
set search_path=public
as $$
declare
  me uuid := auth.uid();
  sid uuid;
  t text := upper(trim(coalesce(p_ticker,'')));
begin
  if me is null or not public.is_admin(me) then raise exception 'owner/admin required'; end if;
  if t !~ '^[A-Z0-9]{1,8}$' then raise exception 'ticker must be 1-8 A-Z/0-9 characters'; end if;
  if length(trim(coalesce(p_name,''))) < 2 then raise exception 'name is too short'; end if;
  if coalesce(p_price,0) <= 0 then raise exception 'price must be positive'; end if;

  insert into public.stock_assets(ticker,name,emoji,description,price,previous_price,created_by)
  values(t,left(trim(p_name),80),left(coalesce(nullif(trim(p_emoji),''),'📈'),12),left(coalesce(p_description,''),1000),p_price,p_price,me)
  returning id into sid;

  insert into public.stock_price_history(stock_id,price,changed_by) values(sid,p_price,me);
  perform public.admin_log('stock_create',null,jsonb_build_object('stock_id',sid,'ticker',t,'price',p_price));
  return sid;
end $$;

create or replace function public.admin_set_stock_price(p_stock uuid,p_price bigint)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  me uuid := auth.uid();
  old_price bigint;
begin
  if me is null or not public.is_admin(me) then raise exception 'owner/admin required'; end if;
  if coalesce(p_price,0) <= 0 then raise exception 'price must be positive'; end if;

  select price into old_price from public.stock_assets where id=p_stock for update;
  if old_price is null then raise exception 'stock not found'; end if;

  update public.stock_assets
  set previous_price=price,price=p_price,updated_at=now()
  where id=p_stock;

  insert into public.stock_price_history(stock_id,price,changed_by) values(p_stock,p_price,me);
  perform public.admin_log('stock_price',null,jsonb_build_object('stock_id',p_stock,'old_price',old_price,'new_price',p_price));
  return jsonb_build_object('ok',true,'old_price',old_price,'new_price',p_price);
end $$;

create or replace function public.admin_update_stock(
  p_stock uuid,
  p_name text default null,
  p_emoji text default null,
  p_description text default null,
  p_active boolean default null
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare me uuid := auth.uid();
begin
  if me is null or not public.is_admin(me) then raise exception 'owner/admin required'; end if;
  update public.stock_assets
  set
    name=case when p_name is null then name else left(trim(p_name),80) end,
    emoji=case when p_emoji is null then emoji else left(coalesce(nullif(trim(p_emoji),''),'📈'),12) end,
    description=case when p_description is null then description else left(p_description,1000) end,
    is_active=coalesce(p_active,is_active),
    updated_at=now()
  where id=p_stock;
  if not found then raise exception 'stock not found'; end if;
  perform public.admin_log('stock_update',null,jsonb_build_object('stock_id',p_stock,'active',p_active));
  return jsonb_build_object('ok',true);
end $$;

create or replace function public.admin_delete_stock(p_stock uuid)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  me uuid := auth.uid();
  holders bigint;
  trade_count bigint;
begin
  if me is null or not public.is_admin(me) then raise exception 'owner/admin required'; end if;
  select count(*) into holders from public.stock_positions where stock_id=p_stock and quantity>0;
  select count(*) into trade_count from public.stock_trades where stock_id=p_stock;
  if holders>0 then raise exception 'stock has holders; pause trading instead of deleting'; end if;
  if trade_count>0 then raise exception 'stock has trade history; pause trading instead of deleting'; end if;
  delete from public.stock_assets where id=p_stock;
  if not found then raise exception 'stock not found'; end if;
  perform public.admin_log('stock_delete',null,jsonb_build_object('stock_id',p_stock));
  return jsonb_build_object('ok',true);
end $$;

create or replace function public.trade_stock(p_stock uuid,p_side text,p_quantity bigint)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  me uuid := auth.uid();
  s public.stock_assets%rowtype;
  bal bigint;
  qty bigint := coalesce(p_quantity,0);
  old_qty bigint := 0;
  old_avg numeric(20,2) := 0;
  total_cost bigint;
  new_qty bigint;
  new_avg numeric(20,2);
begin
  if me is null then raise exception 'not authenticated'; end if;
  if p_side not in ('buy','sell') then raise exception 'invalid side'; end if;
  if qty <= 0 or qty > 1000000 then raise exception 'invalid quantity'; end if;

  select * into s from public.stock_assets where id=p_stock for update;
  if s.id is null then raise exception 'stock not found'; end if;
  if not s.is_active then raise exception 'trading paused'; end if;

  insert into public.game_wallets(user_id) values(me) on conflict(user_id) do nothing;
  select balance into bal from public.game_wallets where user_id=me for update;
  select quantity,average_price into old_qty,old_avg from public.stock_positions
  where user_id=me and stock_id=p_stock for update;

  old_qty := coalesce(old_qty,0);
  old_avg := coalesce(old_avg,0);
  total_cost := s.price * qty;

  if p_side='buy' then
    if bal < total_cost then raise exception 'not enough R₽'; end if;
    new_qty := old_qty + qty;
    new_avg := round(((old_qty::numeric*old_avg)+(qty::numeric*s.price::numeric))/new_qty::numeric,2);
    update public.game_wallets set balance=balance-total_cost,updated_at=now() where user_id=me;
    insert into public.stock_positions(user_id,stock_id,quantity,average_price,updated_at)
    values(me,p_stock,new_qty,new_avg,now())
    on conflict(user_id,stock_id) do update
    set quantity=excluded.quantity,average_price=excluded.average_price,updated_at=now();
  else
    if old_qty < qty then raise exception 'not enough shares'; end if;
    new_qty := old_qty - qty;
    update public.game_wallets set balance=balance+total_cost,updated_at=now() where user_id=me;
    if new_qty=0 then
      delete from public.stock_positions where user_id=me and stock_id=p_stock;
    else
      update public.stock_positions set quantity=new_qty,updated_at=now()
      where user_id=me and stock_id=p_stock;
    end if;
  end if;

  insert into public.stock_trades(user_id,stock_id,side,quantity,price,total)
  values(me,p_stock,p_side,qty,s.price,total_cost);

  return jsonb_build_object(
    'ok',true,'side',p_side,'ticker',s.ticker,'quantity',qty,
    'price',s.price,'total',total_cost,
    'balance',case when p_side='buy' then bal-total_cost else bal+total_cost end,
    'position_quantity',new_qty
  );
end $$;

