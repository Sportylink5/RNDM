-- RNDM Chat v25.4 — virtual stock market
-- Already applied to the connected Rndm Supabase project.
-- Safe to run after v25 on another copy of the project.
-- This is a GAME economy only: all trades use virtual R₽ from game_wallets.

create table if not exists public.stock_assets (
  id uuid primary key default gen_random_uuid(),
  ticker text not null unique,
  name text not null,
  emoji text not null default '📈',
  description text not null default '',
  price bigint not null check(price > 0),
  previous_price bigint not null check(previous_price > 0),
  is_active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ticker ~ '^[A-Z0-9]{1,8}$')
);

create table if not exists public.stock_price_history (
  id bigint generated by default as identity primary key,
  stock_id uuid not null references public.stock_assets(id) on delete cascade,
  price bigint not null check(price > 0),
  changed_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.stock_positions (
  user_id uuid not null references public.profiles(id) on delete cascade,
  stock_id uuid not null references public.stock_assets(id) on delete cascade,
  quantity bigint not null default 0 check(quantity >= 0),
  average_price numeric(20,2) not null default 0 check(average_price >= 0),
  updated_at timestamptz not null default now(),
  primary key(user_id, stock_id)
);

create table if not exists public.stock_trades (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  stock_id uuid not null references public.stock_assets(id) on delete restrict,
  side text not null check(side in ('buy','sell')),
  quantity bigint not null check(quantity > 0),
  price bigint not null check(price > 0),
  total bigint not null check(total > 0),
  created_at timestamptz not null default now()
);

create index if not exists profiles_referred_by_idx on public.profiles(referred_by);
create index if not exists stock_assets_created_by_idx on public.stock_assets(created_by);
create index if not exists stock_assets_active_ticker_idx on public.stock_assets(is_active,ticker);
create index if not exists stock_price_history_stock_created_idx on public.stock_price_history(stock_id,created_at desc);
create index if not exists stock_price_history_changed_by_idx on public.stock_price_history(changed_by);
create index if not exists stock_positions_stock_idx on public.stock_positions(stock_id);
create index if not exists stock_trades_user_created_idx on public.stock_trades(user_id,created_at desc);
create index if not exists stock_trades_stock_created_idx on public.stock_trades(stock_id,created_at desc);

alter table public.stock_assets enable row level security;
alter table public.stock_price_history enable row level security;
alter table public.stock_positions enable row level security;
alter table public.stock_trades enable row level security;

drop policy if exists stocks_read on public.stock_assets;
create policy stocks_read on public.stock_assets for select to authenticated using(true);

drop policy if exists stock_history_read on public.stock_price_history;
create policy stock_history_read on public.stock_price_history for select to authenticated using(true);

drop policy if exists stock_positions_own on public.stock_positions;
create policy stock_positions_own on public.stock_positions for select to authenticated
using(user_id=(select auth.uid()));

drop policy if exists stock_trades_own on public.stock_trades;
create policy stock_trades_own on public.stock_trades for select to authenticated
using(user_id=(select auth.uid()));

revoke all on public.stock_assets from anon;
revoke all on public.stock_price_history from anon;
revoke all on public.stock_positions from anon;
revoke all on public.stock_trades from anon;

grant select on public.stock_assets to authenticated;
