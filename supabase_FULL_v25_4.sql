create or replace function public.trade_stock(p_stock uuid,p_side text,p_quantity bigint)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  me uuid := auth.uid();
  s public.stock_assets%rowtype;
  bal bigint;
  qty bigint := coalesce(p_quantity,0);
  old_qty bigint := 0;
  old_avg numeric(20,2) := 0;
  total_cost bigint;
  new_qty bigint;
  new_avg numeric(20,2);
begin
  if me is null then raise exception 'not authenticated'; end if;
  if p_side not in ('buy','sell') then raise exception 'invalid side'; end if;
  if qty <= 0 or qty > 1000000 then raise exception 'invalid quantity'; end if;

  select * into s from public.stock_assets where id=p_stock for update;
  if s.id is null then raise exception 'stock not found'; end if;
  if not s.is_active then raise exception 'trading paused'; end if;

  insert into public.game_wallets(user_id) values(me) on conflict(user_id) do nothing;
  select balance into bal from public.game_wallets where user_id=me for update;
  select quantity,average_price into old_qty,old_avg from public.stock_positions
  where user_id=me and stock_id=p_stock for update;

  old_qty := coalesce(old_qty,0);
  old_avg := coalesce(old_avg,0);
  total_cost := s.price * qty;

  if p_side='buy' then
    if bal < total_cost then raise exception 'not enough R₽'; end if;
    new_qty := old_qty + qty;
    new_avg := round(((old_qty::numeric*old_avg)+(qty::numeric*s.price::numeric))/new_qty::numeric,2);
    update public.game_wallets set balance=balance-total_cost,updated_at=now() where user_id=me;
    insert into public.stock_positions(user_id,stock_id,quantity,average_price,updated_at)
    values(me,p_stock,new_qty,new_avg,now())
    on conflict(user_id,stock_id) do update
    set quantity=excluded.quantity,average_price=excluded.average_price,updated_at=now();
  else
    if old_qty < qty then raise exception 'not enough shares'; end if;
    new_qty := old_qty - qty;
    update public.game_wallets set balance=balance+total_cost,updated_at=now() where user_id=me;
    if new_qty=0 then
      delete from public.stock_positions where user_id=me and stock_id=p_stock;
    else
      update public.stock_positions set quantity=new_qty,updated_at=now()
      where user_id=me and stock_id=p_stock;
    end if;
  end if;

  insert into public.stock_trades(user_id,stock_id,side,quantity,price,total)
  values(me,p_stock,p_side,qty,s.price,total_cost);

  return jsonb_build_object(
    'ok',true,'side',p_side,'ticker',s.ticker,'quantity',qty,
    'price',s.price,'total',total_cost,
    'balance',case when p_side='buy' then bal-total_cost else bal+total_cost end,
    'position_quantity',new_qty
  );
end $$;

