create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
declare
  base text;
  candidate text;
begin
  base := lower(regexp_replace(coalesce(new.raw_user_meta_data->>'username', split_part(coalesce(new.email,'user'),'@',1), 'user'), '[^a-zA-Z0-9_]+', '', 'g'));
  if length(base) < 3 then base := 'user'; end if;
  base := left(base, 22);
  candidate := base;
  while exists(select 1 from public.profiles where username=candidate) loop
    candidate := left(base,17) || '_' || lpad((floor(random()*10000))::int::text,4,'0');
  end loop;
  insert into public.profiles(id,username,display_name,last_seen)
  values(new.id,candidate,coalesce(nullif(new.raw_user_meta_data->>'display_name',''),candidate),now())
  on conflict(id) do nothing;
  return new;
end $$;

