create or replace function public.admin_create_stock(
  p_ticker text,
  p_name text,
  p_price bigint,
  p_emoji text default '📈',
  p_description text default ''
)
returns uuid
language plpgsql
security definer
set search_path=public
as $$
declare
  me uuid := auth.uid();
  sid uuid;
  t text := upper(trim(coalesce(p_ticker,'')));
begin
  if me is null or not public.is_admin(me) then raise exception 'owner/admin required'; end if;
  if t !~ '^[A-Z0-9]{1,8}$' then raise exception 'ticker must be 1-8 A-Z/0-9 characters'; end if;
  if length(trim(coalesce(p_name,''))) < 2 then raise exception 'name is too short'; end if;
  if coalesce(p_price,0) <= 0 then raise exception 'price must be positive'; end if;

  insert into public.stock_assets(ticker,name,emoji,description,price,previous_price,created_by)
  values(t,left(trim(p_name),80),left(coalesce(nullif(trim(p_emoji),''),'📈'),12),left(coalesce(p_description,''),1000),p_price,p_price,me)
  returning id into sid;

  insert into public.stock_price_history(stock_id,price,changed_by) values(sid,p_price,me);
  perform public.admin_log('stock_create',null,jsonb_build_object('stock_id',sid,'ticker',t,'price',p_price));
  return sid;
end $$;

