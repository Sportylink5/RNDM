-- RNDM Chat v22 Supabase upgrade
-- Run AFTER supabase_schema.sql and supabase_v20_upgrade.sql.
-- Adds cloud state sync, real Channels and real RNDM Video.

create extension if not exists pgcrypto;

-- =========================================================
-- 1) CROSS-DEVICE USER STATE (cat, XP, stars, settings, etc.)
-- =========================================================
create table if not exists public.user_state (
  user_id uuid not null references public.profiles(id) on delete cascade,
  key text not null,
  value jsonb not null default 'null'::jsonb,
  updated_at timestamptz not null default now(),
  primary key(user_id,key)
);

alter table public.user_state enable row level security;

drop policy if exists user_state_read_own on public.user_state;
create policy user_state_read_own on public.user_state
for select to authenticated using(user_id=auth.uid());

drop policy if exists user_state_insert_own on public.user_state;
create policy user_state_insert_own on public.user_state
for insert to authenticated with check(user_id=auth.uid());

drop policy if exists user_state_update_own on public.user_state;
create policy user_state_update_own on public.user_state
for update to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());

drop policy if exists user_state_delete_own on public.user_state;
create policy user_state_delete_own on public.user_state
for delete to authenticated using(user_id=auth.uid());

grant select,insert,update,delete on public.user_state to authenticated;

-- =========================================================
-- 2) REAL CHANNELS
-- =========================================================
create table if not exists public.rndm_channels (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null check(char_length(name) between 2 and 80),
  handle text unique,
  description text not null default '',
  emoji text not null default '📡',
  avatar_url text,
  promo_subscribers integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.rndm_channel_subscriptions (
  channel_id uuid not null references public.rndm_channels(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(channel_id,user_id)
);

create table if not exists public.rndm_channel_posts (
  id uuid primary key default gen_random_uuid(),
  channel_id uuid not null references public.rndm_channels(id) on delete cascade,
  author_id uuid not null references public.profiles(id) on delete cascade,
  body text not null default '',
  attachment_url text,
  attachment_type text,
  attachment_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.rndm_channel_comments (
  id bigint generated by default as identity primary key,
  post_id uuid not null references public.rndm_channel_posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check(char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);

create table if not exists public.rndm_channel_reactions (
  post_id uuid not null references public.rndm_channel_posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  emoji text not null default '❤️',
  created_at timestamptz not null default now(),
  primary key(post_id,user_id,emoji)
);

create index if not exists rndm_channels_created_idx on public.rndm_channels(created_at desc);
create index if not exists rndm_posts_channel_idx on public.rndm_channel_posts(channel_id,created_at desc);
create index if not exists rndm_comments_post_idx on public.rndm_channel_comments(post_id,created_at);

create or replace function public.is_channel_owner(cid uuid, uid uuid default auth.uid())
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.rndm_channels where id=cid and owner_id=uid)
$$;

alter table public.rndm_channels enable row level security;
alter table public.rndm_channel_subscriptions enable row level security;
alter table public.rndm_channel_posts enable row level security;
alter table public.rndm_channel_comments enable row level security;
