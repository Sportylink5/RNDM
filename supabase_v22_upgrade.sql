create table if not exists public.rndm_videos (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check(char_length(title) between 1 and 120),
  description text not null default '',
  video_url text not null,
  view_count bigint not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.rndm_video_likes (
  video_id uuid not null references public.rndm_videos(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(video_id,user_id)
);

create table if not exists public.rndm_video_comments (
  id bigint generated by default as identity primary key,
  video_id uuid not null references public.rndm_videos(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check(char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

create table if not exists public.rndm_follows (
  follower_id uuid not null references public.profiles(id) on delete cascade,
  followee_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(follower_id,followee_id),
  check(follower_id<>followee_id)
);

create index if not exists rndm_videos_created_idx on public.rndm_videos(created_at desc);
create index if not exists rndm_video_comments_idx on public.rndm_video_comments(video_id,created_at);

