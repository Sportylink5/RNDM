create or replace function public.increment_rndm_video_view(video uuid)
returns void language plpgsql security definer set search_path=public as $$
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  update public.rndm_videos set view_count=view_count+1 where id=video;
end $$;
grant execute on function public.increment_rndm_video_view(uuid) to authenticated;

