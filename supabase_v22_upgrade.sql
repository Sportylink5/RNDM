grant select,insert,update,delete on public.rndm_channels to authenticated;
grant select,insert,delete on public.rndm_channel_subscriptions to authenticated;
grant select,insert,update,delete on public.rndm_channel_posts to authenticated;
grant select,insert,delete on public.rndm_channel_comments to authenticated;
grant select,insert,delete on public.rndm_channel_reactions to authenticated;

