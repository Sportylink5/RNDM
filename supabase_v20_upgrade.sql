-- ---------------- GAME WALLET / LOANS / APARTMENTS ----------------
-- Everything in this section is virtual game currency. It is NOT a real loan or payment system.
create table if not exists public.game_wallets (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  balance bigint not null default 1500000 check(balance >= 0),
  updated_at timestamptz not null default now()
);

insert into public.game_wallets(user_id)
select id from public.profiles
on conflict(user_id) do nothing;

create or replace function public.ensure_game_wallet()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.game_wallets(user_id) values(new.id) on conflict(user_id) do nothing;
  return new;
end $$;

drop trigger if exists on_profile_game_wallet on public.profiles;
create trigger on_profile_game_wallet after insert on public.profiles
for each row execute function public.ensure_game_wallet();

