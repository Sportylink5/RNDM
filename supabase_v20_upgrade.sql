create or replace function public.take_demo_loan(amount bigint, months int)
returns uuid language plpgsql security definer set search_path=public as $$
declare
  me uuid:=auth.uid();
  rate numeric(6,2);
  total bigint;
  lid uuid;
  active_debt bigint;
begin
  if me is null then raise exception 'not authenticated'; end if;
  if amount < 10000 or amount > 5000000 then raise exception 'amount must be from 10000 to 5000000'; end if;
  if months not in (3,6,12,24) then raise exception 'term must be 3, 6, 12 or 24 months'; end if;
  select coalesce(sum(remaining),0) into active_debt from public.game_loans where user_id=me and status='active';
  if active_debt + amount > 7000000 then raise exception 'demo credit limit exceeded'; end if;
  rate := case months when 3 then 5 when 6 then 8 when 12 then 12 else 18 end;
  total := round(amount * (1 + rate/100.0));
  insert into public.game_wallets(user_id) values(me) on conflict(user_id) do nothing;
  update public.game_wallets set balance=balance+amount,updated_at=now() where user_id=me;
  insert into public.game_loans(user_id,principal,rate_percent,term_months,total_due,remaining)
  values(me,amount,rate,months,total,total) returning id into lid;
  return lid;
end $$;

create or replace function public.repay_demo_loan(loan_id uuid, amount bigint)
returns bigint language plpgsql security definer set search_path=public as $$
declare
  me uuid:=auth.uid();
  rem bigint;
  bal bigint;
  pay bigint;
begin
  if me is null then raise exception 'not authenticated'; end if;
  select remaining into rem from public.game_loans where id=loan_id and user_id=me and status='active' for update;
  if rem is null then raise exception 'active loan not found'; end if;
  select balance into bal from public.game_wallets where user_id=me for update;
  if amount <= 0 then raise exception 'invalid amount'; end if;
  pay:=least(amount,rem);
  if bal < pay then raise exception 'not enough demo balance'; end if;
  update public.game_wallets set balance=balance-pay,updated_at=now() where user_id=me;
  update public.game_loans set remaining=remaining-pay,status=case when remaining-pay<=0 then 'paid' else 'active' end where id=loan_id;
  return rem-pay;
end $$;

create or replace function public.buy_demo_property(property uuid)
returns void language plpgsql security definer set search_path=public as $$
declare
  me uuid:=auth.uid();
  p bigint;
  bal bigint;
begin
  if me is null then raise exception 'not authenticated'; end if;
  select price into p from public.demo_properties where id=property;
  if p is null then raise exception 'property not found'; end if;
  if exists(select 1 from public.owned_properties where user_id=me and property_id=property) then raise exception 'already owned'; end if;
  insert into public.game_wallets(user_id) values(me) on conflict(user_id) do nothing;
  select balance into bal from public.game_wallets where user_id=me for update;
  if bal < p then raise exception 'not enough demo balance'; end if;
  update public.game_wallets set balance=balance-p,updated_at=now() where user_id=me;
  insert into public.owned_properties(user_id,property_id,bought_price) values(me,property,p);
end $$;

grant execute on function public.take_demo_loan(bigint,int) to authenticated;
grant execute on function public.repay_demo_loan(uuid,bigint) to authenticated;
grant execute on function public.buy_demo_property(uuid) to authenticated;

