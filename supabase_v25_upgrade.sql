alter table public.profiles add column if not exists referral_code text;
alter table public.profiles add column if not exists referred_by uuid references public.profiles(id) on delete set null;
alter table public.profiles add column if not exists referral_count integer not null default 0;
alter table public.profiles add column if not exists referral_stars_earned bigint not null default 0;
alter table public.profiles add column if not exists referral_coins_earned bigint not null default 0;

create unique index if not exists profiles_referral_code_uq on public.profiles(referral_code) where referral_code is not null;

create or replace function public.referral_code_for(uid uuid)
returns text language sql immutable as $$
  select 'R' || upper(substr(replace(uid::text,'-',''),1,11));
$$;

update public.profiles
set referral_code=public.referral_code_for(id)
where referral_code is null or referral_code='';

create or replace function public.assign_referral_code()
returns trigger language plpgsql as $$
begin
  if new.referral_code is null or new.referral_code='' then
    new.referral_code := public.referral_code_for(new.id);
  end if;
  return new;
end $$;

drop trigger if exists trg_profile_referral_code on public.profiles;
create trigger trg_profile_referral_code
before insert on public.profiles
for each row execute function public.assign_referral_code();

create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  referrer_id uuid not null references public.profiles(id) on delete cascade,
  referred_id uuid not null unique references public.profiles(id) on delete cascade,
  referral_code text not null,
  referrer_stars bigint not null default 50,
  referred_stars bigint not null default 25,
  referrer_coins bigint not null default 1000,
  referred_coins bigint not null default 250,
  created_at timestamptz not null default now()
);

alter table public.referrals enable row level security;
drop policy if exists referrals_read_own on public.referrals;
create policy referrals_read_own on public.referrals for select to authenticated
using(referrer_id=auth.uid() or referred_id=auth.uid() or public.is_staff());
grant select on public.referrals to authenticated;

create or replace function public.add_cat_coins(target uuid, delta bigint)
returns void language plpgsql security definer set search_path=public as $$
declare oldv jsonb; nc bigint; nt bigint;
begin
  select value into oldv from public.user_state where user_id=target and key='ls:rndmCatV2' for update;
  oldv := coalesce(oldv,'{}'::jsonb);
  begin nc := coalesce((oldv->>'coins')::bigint,0)+delta; exception when others then nc:=delta; end;
  begin nt := coalesce((oldv->>'totalCoins')::bigint,0)+delta; exception when others then nt:=delta; end;
  oldv := jsonb_set(oldv,'{coins}',to_jsonb(greatest(0,nc)),true);
  oldv := jsonb_set(oldv,'{totalCoins}',to_jsonb(greatest(0,nt)),true);
  oldv := jsonb_set(oldv,'{lastSeen}',to_jsonb((extract(epoch from now())*1000)::bigint),true);
  insert into public.user_state(user_id,key,value,updated_at)
  values(target,'ls:rndmCatV2',oldv,now())
  on conflict(user_id,key) do update set value=excluded.value,updated_at=now();
end $$;
revoke all on function public.add_cat_coins(uuid,bigint) from public;

create or replace function public.ensure_referral_code()
returns text language plpgsql security definer set search_path=public as $$
declare c text;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  update public.profiles set referral_code=public.referral_code_for(id)
  where id=auth.uid() and (referral_code is null or referral_code='');
  select referral_code into c from public.profiles where id=auth.uid();
  return c;
end $$;
grant execute on function public.ensure_referral_code() to authenticated;

create or replace function public.claim_referral(ref_code text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  me uuid:=auth.uid(); ref uuid; current_ref uuid; inserted integer:=0; ref_name text;
  code text:=upper(trim(coalesce(ref_code,'')));
begin
  if me is null then raise exception 'not authenticated'; end if;
  if code='' then raise exception 'empty referral code'; end if;
  select referred_by into current_ref from public.profiles where id=me for update;
  select id,username into ref,ref_name from public.profiles where upper(referral_code)=code limit 1;
  if ref is null then raise exception 'referral code not found'; end if;
  if ref=me then raise exception 'cannot refer yourself'; end if;
  if current_ref is not null then
    return jsonb_build_object('ok',true,'status','already_claimed','referrer_id',current_ref);
  end if;

  insert into public.referrals(referrer_id,referred_id,referral_code)
  values(ref,me,code) on conflict(referred_id) do nothing;
  get diagnostics inserted = row_count;
  if inserted=0 then
    select referrer_id into current_ref from public.referrals where referred_id=me;
    update public.profiles set referred_by=current_ref where id=me and referred_by is null;
    return jsonb_build_object('ok',true,'status','already_claimed','referrer_id',current_ref);
  end if;

  update public.profiles set
    referred_by=ref,
    stars=stars+25,
    xp=xp+100
  where id=me;

  update public.profiles set
    stars=stars+50,
    xp=xp+250,
    referral_count=referral_count+1,
    referral_stars_earned=referral_stars_earned+50,
    referral_coins_earned=referral_coins_earned+1000
  where id=ref;

  perform public.add_cat_coins(ref,1000);
  perform public.add_cat_coins(me,250);

  insert into public.notifications(user_id,kind,title,body,link)
  values
    (ref,'referral','🎉 Новый реферал','Кто-то зарегистрировался по вашей ссылке. +50 ⭐, +250 XP, +1000 🪙','cat.html'),
    (me,'referral','🎁 Реферальный бонус','Бонус за регистрацию по ссылке: +25 ⭐, +100 XP, +250 🪙','cat.html');

  return jsonb_build_object('ok',true,'status','claimed','referrer_id',ref,'referrer_username',ref_name,'stars',25,'coins',250,'xp',100);
end $$;
grant execute on function public.claim_referral(text) to authenticated;

