create or replace function public.admin_delete_app_profile(target uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare myrole text; targetrole text;
begin
  select app_role into myrole from public.profiles where id=auth.uid();
  select app_role into targetrole from public.profiles where id=target;
  if myrole<>'owner' then raise exception 'owner required'; end if;
  if target=auth.uid() then raise exception 'owner cannot delete self'; end if;
  if public.role_rank(myrole)<=public.role_rank(targetrole) then raise exception 'cannot delete equal/higher role'; end if;
  perform public.admin_log('delete_app_profile',target,jsonb_build_object('note','auth.users entry remains; app profile/content deleted'));
  delete from public.profiles where id=target;
  return jsonb_build_object('ok',true,'auth_user_deleted',false);
end $$;
grant execute on function public.admin_delete_app_profile(uuid) to authenticated;
